"""HSK-format exercises: paper structure, question bank, practice sets and results.

- `data/exercises/formats.json`: the parts of each paper (version → level → section).
- `data/exercises/bank.json`: the reviewed question bank, built from `src/*.yaml` by
  `scripts/build_exercises.py`, which also checks each item's vocabulary and records
  the versions (2.0 / 3.0) whose word lists cover it.
- Items generated by Claude for a user (`GeneratedExercise`) join that user's pool.

A practice set prefers the items the user has not answered yet, then the ones
answered longest ago.
"""

from __future__ import annotations

import csv
import json
import random
import re
from datetime import datetime
from functools import lru_cache
from pathlib import Path
from typing import Any

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.models import ExerciseResult, GeneratedExercise
from app.services.exercise_schema import chinese_texts

DATA_DIR = Path(__file__).resolve().parents[2] / "data" / "exercises"
SECTIONS = ("listening", "writing")
LEVELS = (1, 2, 3)
GROUP_TYPES = {"pic_match", "word_match"}  # one item = 6 options shared by 5 questions
GROUP_SIZE = 5


@lru_cache(maxsize=1)
def formats() -> dict[str, Any]:
    with open(DATA_DIR / "formats.json", encoding="utf-8") as f:
        data = json.load(f)
    data.pop("_source", None)
    return data


@lru_cache(maxsize=1)
def bank() -> list[dict[str, Any]]:
    path = DATA_DIR / "bank.json"
    if not path.exists():
        return []
    with open(path, encoding="utf-8") as f:
        return json.load(f)["items"]


def parts(version: str, level: int, section: str) -> list[dict[str, Any]]:
    return formats().get(version, {}).get(str(level), {}).get(section, [])


def find_part(version: str, level: int, section: str, part_key: str) -> dict[str, Any] | None:
    return next((p for p in parts(version, level, section) if p["part"] == part_key), None)


def part_slots(part: dict[str, Any]) -> list[tuple[str, int]]:
    """(item type, number of questions) the part is made of."""
    if part["type"] == "mix":
        return [(m["type"], m["count"]) for m in part["mix"]]
    if part["type"] == "unavailable":
        return []
    return [(part["type"], part["count"])]


def questions_in(item: dict[str, Any]) -> int:
    return len(item["items"]) if item["type"] in GROUP_TYPES else 1


# --------------------------------------------------------------------------- pools


def _generated(db: Session, user_id: int, version: str, level: int, item_type: str) -> list[dict[str, Any]]:
    rows = db.execute(
        select(GeneratedExercise).where(
            GeneratedExercise.user_id == user_id,
            GeneratedExercise.version == version,
            GeneratedExercise.level == level,
            GeneratedExercise.item_type == item_type,
        )
    ).scalars()
    items = []
    for row in rows:
        item = json.loads(row.payload)
        item["id"] = f"gen-{row.id}"
        item["generated"] = True
        items.append(item)
    return items


def pool(db: Session, user_id: int, version: str, level: int, item_type: str) -> list[dict[str, Any]]:
    """Bank items valid for `version` at `level`, plus the user's generated ones."""
    own = [
        i for i in bank() if i["type"] == item_type and i["level"] == level and version in i.get("versions", [])
    ]
    return own + _generated(db, user_id, version, level, item_type)


def _last_seen(db: Session, user_id: int) -> dict[str, datetime]:
    """When the user last answered each item (group items count by group id)."""
    seen: dict[str, datetime] = {}
    rows = db.execute(
        select(ExerciseResult.details, ExerciseResult.created_at).where(
            ExerciseResult.user_id == user_id, ExerciseResult.section.in_(SECTIONS)
        )
    ).all()
    for details, created_at in rows:
        try:
            answers = json.loads(details or "[]")
        except json.JSONDecodeError:
            continue
        for answer in answers:
            item_id = str(answer.get("id", "")).split("#")[0]
            if item_id and (item_id not in seen or created_at > seen[item_id]):
                seen[item_id] = created_at
    return seen


def pick(items: list[dict[str, Any]], questions: int, seen: dict[str, datetime], rng: random.Random) -> list[dict[str, Any]]:
    """Enough items for `questions` questions: never-answered first, then oldest."""
    shuffled = items[:]
    rng.shuffle(shuffled)
    shuffled.sort(key=lambda i: (i["id"] in seen, seen.get(i["id"], datetime.min)))
    chosen: list[dict[str, Any]] = []
    total = 0
    for item in shuffled:
        if total >= questions:
            break
        chosen.append(item)
        total += questions_in(item)
    return chosen


# --------------------------------------------------------------------------- catalog and sets


def catalog(db: Session, user_id: int, version: str, level: int, section: str) -> list[dict[str, Any]]:
    results = db.execute(
        select(ExerciseResult)
        .where(
            ExerciseResult.user_id == user_id,
            ExerciseResult.version == version,
            ExerciseResult.level == level,
            ExerciseResult.section == section,
        )
        .order_by(ExerciseResult.created_at.desc())
    ).scalars().all()
    out = []
    for part in parts(version, level, section):
        available = 0
        for item_type, _ in part_slots(part):
            available += sum(questions_in(i) for i in pool(db, user_id, version, level, item_type))
        mine = [r for r in results if r.part_key == part["part"]]
        out.append(
            {
                **part,
                "available": available,
                "attempts": len(mine),
                "last": {"score": mine[0].score, "total": mine[0].total, "at": mine[0].created_at} if mine else None,
                "best": max(({"score": r.score, "total": r.total} for r in mine), key=lambda x: x["score"] / max(1, x["total"]), default=None),
            }
        )
    return out


def build_set(
    db: Session, user_id: int, version: str, level: int, section: str, part_key: str, seed: int | None = None
) -> dict[str, Any]:
    """A practice set for one part, or the whole section (`part_key="all"`)."""
    chosen_parts = parts(version, level, section) if part_key == "all" else [find_part(version, level, section, part_key)]
    if not chosen_parts or chosen_parts[0] is None:
        raise KeyError(part_key)
    rng = random.Random(seed)
    seen = _last_seen(db, user_id)
    out = []
    for part in chosen_parts:
        slots = part_slots(part)
        if not slots:
            continue
        items: list[dict[str, Any]] = []
        for item_type, count in slots:
            items += pick(pool(db, user_id, version, level, item_type), count, seen, rng)
        out.append({**part, "items": items})
    return {"version": version, "level": level, "section": section, "part": part_key, "parts": out}


def save_result(
    db: Session,
    *,
    user_id: int,
    version: str,
    level: int,
    section: str,
    part_key: str,
    answers: list[dict[str, Any]],
) -> ExerciseResult:
    row = ExerciseResult(
        user_id=user_id,
        version=version,
        level=level,
        section=section,
        part_key=part_key,
        score=sum(1 for a in answers if a.get("correct")),
        total=len(answers),
        details=json.dumps([{"id": a["id"], "correct": bool(a.get("correct"))} for a in answers]),
        created_at=datetime.utcnow(),
    )
    db.add(row)
    db.flush()
    return row


def save_generated(
    db: Session, *, user_id: int, version: str, level: int, item_type: str, items: list[dict[str, Any]], model_id: str
) -> list[dict[str, Any]]:
    out = []
    now = datetime.utcnow()
    for item in items:
        row = GeneratedExercise(
            user_id=user_id,
            version=version,
            level=level,
            item_type=item_type,
            payload=json.dumps(item, ensure_ascii=False),
            model_id=model_id[:64],
            created_at=now,
        )
        db.add(row)
        db.flush()
        out.append({**item, "id": f"gen-{row.id}", "generated": True})
    return out


# --------------------------------------------------------------------------- vocabulary (for generation)

_HAN_RUN = re.compile(r"[一-鿿]")
# Common names in the papers, accepted in generated items.
NAME_CHARS = set("王李张刘陈杨赵黄周吴明红丽华")


@lru_cache(maxsize=None)
def vocabulary(version: str, level: int) -> tuple[str, ...]:
    """Cumulative word list of `version` up to `level`."""
    folder = "hsk2" if version == "2.0" else "hsk3"
    words: list[str] = []
    for lv in range(1, level + 1):
        with open(DATA_DIR.parent / folder / f"hsk{lv}.csv", encoding="utf-8-sig") as f:
            words += [row["hanzi"].strip() for row in csv.DictReader(f)]
    return tuple(dict.fromkeys(words))


@lru_cache(maxsize=None)
def known_chars(version: str, level: int) -> frozenset[str]:
    return frozenset(c for w in vocabulary(version, level) for c in w if _HAN_RUN.match(c)) | NAME_CHARS


def unknown_chars(item: dict[str, Any], version: str, level: int) -> set[str]:
    chars = known_chars(version, level)
    return {c for text in chinese_texts(item) for c in text if _HAN_RUN.match(c) and c not in chars}


def recent_texts(items: list[dict[str, Any]], limit: int = 30) -> list[str]:
    """Short summaries of existing items, so a new series does not repeat them."""
    out = []
    for item in items[-limit:]:
        if item.get("audio"):
            out.append(" / ".join(line["t"] for line in item["audio"])[:60])
        elif item.get("items"):
            out.append(" / ".join(q["audio"][0]["t"] for q in item["items"])[:60])
        elif item.get("before") is not None:
            out.append(f"{item['before']}（{item['pinyin']}）{item['after']}")
        elif item.get("word"):
            out.append(item["word"])
        elif item.get("answers"):
            out.append(item["answers"][0])
    return out
